  created_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  updated_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  CONSTRAINT uq_doctype_name UNIQUE (name),
  CONSTRAINT ck_doctype_active CHECK (active IN (0,1))
);
