CREATE TABLE IF NOT EXISTS requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracking_no VARCHAR(40) NOT NULL,
  user_id BIGINT NOT NULL,
  document_type_id BIGINT NULL,
  document_type VARCHAR(80) NOT NULL,
  purpose VARCHAR(80) NOT NULL,
  preferred_claim_date DATE NULL,
  comments VARCHAR(500) NULL,
  form_data TEXT NULL,
  attachment_path VARCHAR(255) NULL,
  attachment_name VARCHAR(255) NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'pending',
  claim_date DATE NULL,
  resident_note VARCHAR(500) NULL,
  admin_notes VARCHAR(1000) NULL,
  client_token VARCHAR(64) NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  updated_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  CONSTRAINT uq_requests_tracking UNIQUE (tracking_no),
  CONSTRAINT uq_requests_token UNIQUE (user_id, client_token),
  CONSTRAINT ck_requests_status CHECK (status IN ('pending','processing','ready','completed','rejected')),
  CONSTRAINT fk_requests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_requests_type FOREIGN KEY (document_type_id) REFERENCES document_types (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_requests_user ON requests (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_requests_status ON requests (status, created_at);

CREATE TABLE IF NOT EXISTS request_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL,
  event VARCHAR(12) NOT NULL,
  status VARCHAR(12) NOT NULL,
  note VARCHAR(500) NULL,
  actor_user_id BIGINT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  CONSTRAINT fk_rhist_request FOREIGN KEY (request_id) REFERENCES requests (id) ON DELETE CASCADE,
  CONSTRAINT fk_rhist_actor FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_rhist_request ON request_history (request_id, id);

-- One row per uploaded requirement (Valid ID, Cedula, ...). The old single-file columns on `requests` are no longer used.
CREATE TABLE IF NOT EXISTS request_files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL,
  field_key VARCHAR(40) NOT NULL,
  label VARCHAR(80) NOT NULL,
  stored_path VARCHAR(255) NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  CONSTRAINT fk_rfiles_request FOREIGN KEY (request_id) REFERENCES requests (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_rfiles_request ON request_files (request_id);

CREATE TABLE IF NOT EXISTS announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(150) NOT NULL,
  message VARCHAR(2000) NOT NULL,
  status VARCHAR(10) NOT NULL DEFAULT 'published',
  published_at TIMESTAMP(0) NULL,
  created_by BIGINT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  updated_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  CONSTRAINT ck_ann_status CHECK (status IN ('published','draft')),
  CONSTRAINT fk_ann_user FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_ann_feed ON announcements (status, published_at);

-- @pg-only-begin
-- Keep users.updated_at current on every UPDATE (the MySQL "ON UPDATE CURRENT_TIMESTAMP" equivalent).
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.updated_at := timezone('utc', now());
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_users_updated_at ON users;
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- SECURITY: Supabase publishes every table in "public" through its REST API.
-- Turn on Row Level Security (with NO policies = nobody but the server may touch the data)
-- and remove the API roles' privileges. The Node server connects with the database owner
-- role (postgres), which is not affected by this.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE email_otps ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE password_resets ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE document_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE request_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE request_files ENABLE ROW LEVEL SECURITY;
ALTER TABLE announcements ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON TABLE users, email_otps, sessions, password_resets, audit_log, notifications, document_types, requests, request_history, request_files, announcements FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON TABLE users, email_otps, sessions, password_resets, audit_log, notifications, document_types, requests, request_history, request_files, announcements FROM authenticated;
  END IF;
END
$$;
-- @pg-only-end
