-- BarangayDocs authentication schema for Supabase (PostgreSQL 15+).
-- Run it in the Supabase dashboard: SQL Editor -> New query -> paste this whole file -> Run.
-- (Or: npm run db:init, which applies it using DATABASE_URL.)
-- All timestamps are stored in UTC. The Node server is the ONLY client of these tables.

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  citizen_id VARCHAR(20) NULL,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  phone VARCHAR(11) NULL,
  date_of_birth DATE NULL,
  role VARCHAR(10) NOT NULL DEFAULT 'resident',
  account_status VARCHAR(10) NOT NULL DEFAULT 'pending',
  email_verified SMALLINT NOT NULL DEFAULT 0,
  email_verified_at TIMESTAMP(0) NULL,
  id_file_path VARCHAR(255) NULL,
  id_file_name VARCHAR(255) NULL,
  rejection_reason VARCHAR(500) NULL,
  approved_at TIMESTAMP(0) NULL,
  approved_by BIGINT NULL,
  rejected_at TIMESTAMP(0) NULL,
  rejected_by BIGINT NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  updated_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT uq_users_citizen_id UNIQUE (citizen_id),
  CONSTRAINT ck_users_email_lower CHECK (email = lower(email)),
  CONSTRAINT ck_users_role CHECK (role IN ('admin','resident')),
  CONSTRAINT ck_users_status CHECK (account_status IN ('pending','approved','rejected')),
  CONSTRAINT ck_users_verified CHECK (email_verified IN (0,1)),
  CONSTRAINT fk_users_approved_by FOREIGN KEY (approved_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_users_rejected_by FOREIGN KEY (rejected_by) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_users_queue ON users (role, account_status, email_verified);

CREATE TABLE IF NOT EXISTS email_otps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL,
  purpose VARCHAR(10) NOT NULL DEFAULT 'register',
  otp_hash VARCHAR(64) NOT NULL,
  expires_at TIMESTAMP(0) NOT NULL,
  verified_at TIMESTAMP(0) NULL,
  invalidated_at TIMESTAMP(0) NULL,
  attempts SMALLINT NOT NULL DEFAULT 0,
  ip_address VARCHAR(45) NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  CONSTRAINT ck_otps_purpose CHECK (purpose IN ('register','reset'))
);
CREATE INDEX IF NOT EXISTS idx_otps_lookup ON email_otps (email, purpose, created_at);

CREATE TABLE IF NOT EXISTS sessions (
  id VARCHAR(64) PRIMARY KEY,
  user_id BIGINT NOT NULL,
  csrf_token VARCHAR(64) NOT NULL,
  ip_address VARCHAR(45) NULL,
  user_agent VARCHAR(255) NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  last_seen_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  expires_at TIMESTAMP(0) NOT NULL,
  CONSTRAINT fk_sessions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON sessions (expires_at);

CREATE TABLE IF NOT EXISTS password_resets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  token_hash VARCHAR(64) NOT NULL,
  expires_at TIMESTAMP(0) NOT NULL,
  used_at TIMESTAMP(0) NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  CONSTRAINT uq_resets_token UNIQUE (token_hash),
  CONSTRAINT fk_resets_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_resets_user ON password_resets (user_id);

CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id BIGINT NULL,
  action VARCHAR(60) NOT NULL,
  target_user_id BIGINT NULL,
  details TEXT NULL,
  ip_address VARCHAR(45) NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  CONSTRAINT fk_audit_actor FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT fk_audit_target FOREIGN KEY (target_user_id) REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_audit_target ON audit_log (target_user_id);
CREATE INDEX IF NOT EXISTS idx_audit_action ON audit_log (action, created_at);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  type VARCHAR(20) NOT NULL DEFAULT 'account',
  title VARCHAR(150) NOT NULL,
  message VARCHAR(500) NOT NULL,
  tracking_no VARCHAR(40) NULL,
  ref_key VARCHAR(80) NULL,
  created_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now())),
  read_at TIMESTAMP(0) NULL,
  CONSTRAINT ck_notif_type CHECK (type IN ('ready','approved','processing','submitted','rejected','announcement','account')),
  CONSTRAINT fk_notif_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications (user_id, created_at);
-- Simple key/value settings (e.g. hall_open = '1' or '0' for the Barangay Hall open/closed switch)
CREATE TABLE IF NOT EXISTS settings (
  name VARCHAR(60) PRIMARY KEY,
  value VARCHAR(255) NOT NULL,
  updated_at TIMESTAMP(0) NOT NULL DEFAULT (timezone('utc', now()))
);

-- @pg-only-begin
-- Existing databases: add the new column before the index below needs it (no data is touched).
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS ref_key VARCHAR(80) NULL;
-- @pg-only-end
-- One notification per (resident, event): re-running a status change or a publish can never create a duplicate.
CREATE UNIQUE INDEX IF NOT EXISTS uq_notif_ref ON notifications (user_id, ref_key);

CREATE TABLE IF NOT EXISTS document_types (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
