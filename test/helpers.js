function convertSchema(sql) {   // database/schema.sql is PostgreSQL; the test DB is SQLite
  return sql.replace(/-- @pg-only-begin[\s\S]*?-- @pg-only-end/g, '')
    .replace(/BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/g, 'INTEGER PRIMARY KEY AUTOINCREMENT')
    .replace(/\bTIMESTAMP\(0\)/g, 'TEXT').replace(/\bDATE\b/g, 'TEXT').replace(/\b(BIGINT|SMALLINT)\b/g, 'INTEGER').replace(/\bVARCHAR\(\d+\)/g, 'TEXT')
    .replace(/DEFAULT \(timezone\('utc', now\(\)\)\)/g, 'DEFAULT CURRENT_TIMESTAMP');
}
function createSqliteDb() {
  const { DatabaseSync } = require('node:sqlite');
  const d = new DatabaseSync(':memory:'); d.exec('PRAGMA foreign_keys=ON');
  d.exec(convertSchema(fs.readFileSync(path.join(ROOT, 'database', 'schema.sql'), 'utf8')));
  const nn = p => (p || []).map(v => (v === undefined ? null : v));
  const q = {
    all: async (sql, p) => d.prepare(sql).all(...nn(p)),
    get: async (sql, p) => d.prepare(sql).get(...nn(p)) || null,
    run: async (sql, p) => { try { const r = d.prepare(sql).run(...nn(p)); return { affectedRows: Number(r.changes), insertId: Number(r.lastInsertRowid) }; } catch (e) { if (/UNIQUE constraint/.test(e.message)) e.code = 'DUPLICATE_KEY'; throw e; } }
  };
  let chain = Promise.resolve();
  return Object.assign({}, q, {
    tx(fn) {
      const job = chain.then(async () => { d.exec('BEGIN'); try { const o = await fn(q); d.exec('COMMIT'); return o; } catch (e) { d.exec('ROLLBACK'); throw e; } });
      chain = job.catch(() => {}); return job;
    }, raw: d
  });
}
function startMailServer() {
  const box = { messages: [], failWith: 0 };
  const srv = http.createServer((req, res) => {
    let b = ''; req.on('data', c => (b += c)); req.on('end', () => {
      if (box.failWith) { res.writeHead(box.failWith); return res.end('{}'); }
      if (req.headers['api-key'] !== 'test-key' || req.url !== '/v3/smtp/email') { res.writeHead(401); return res.end('{}'); }
      const m = JSON.parse(b); box.messages.push({ to: m.to[0].email, subject: m.subject, html: m.htmlContent, text: m.textContent, from: m.sender.email });
      res.writeHead(201, { 'Content-Type': 'application/json' }); res.end('{"messageId":"x"}');
    });
  });
  return new Promise(r => srv.listen(0, '127.0.0.1', () => { box.url = 'http://127.0.0.1:' + srv.address().port; box.close = () => srv.close(); box.last = to => [...box.messages].reverse().find(m => m.to === to);
    box.otpFor = to => { const m = box.last(to); const x = m && /code is: (\d{6})/.exec(m.text); return x && x[1]; }; r(box); }));
}
async function startServer({ mailConfigured = true } = {}) {
  const mail = await startMailServer();
  const uploadDir = fs.mkdtempSync(path.join(os.tmpdir(), 'bd-ids-'));
  const cfg = loadConfig({ SESSION_SECRET: 'x'.repeat(48), UPLOAD_DIR: uploadDir, APP_URL: 'http://localhost', MAIL_PROVIDER: 'brevo', MAIL_API_KEY: mailConfigured ? 'test-key' : '', MAIL_FROM_ADDRESS: mailConfigured ? 'noreply@test.local' : '', MAIL_API_BASE_URL: mail.url, OTP_RESEND_COOLDOWN_SEC: '30' }, ROOT);
  cfg.uploadDir = uploadDir;
  const db = createSqliteDb(), log = { error() {}, log() {} };
  const app = createApp({ config: cfg, db, mailer: createMailer(cfg.mail, log), log });
  const server = http.createServer(app.listener);
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  const base = 'http://127.0.0.1:' + server.address().port;
  return { base, db, mail, cfg, app, uploadDir, close() { server.close(); app.close(); mail.close(); } };
}
/* minimal browser-like client with a cookie jar */
class Client {
  constructor(base) { this.base = base; this.cookie = ''; this.csrf = ''; }
  async req(method, p, { json, form, headers = {}, csrf = true } = {}) {
    const h = Object.assign({}, headers); let body;
    if (json !== undefined) { h['Content-Type'] = 'application/json'; body = JSON.stringify(json); }
    if (form) { h['Content-Type'] = 'multipart/form-data; boundary=' + form.boundary; body = form.body; }
    if (this.cookie) h.Cookie = this.cookie;
    if (csrf && this.csrf) h['X-CSRF-Token'] = this.csrf;
    const r = await fetch(this.base + p, { method, headers: h, body, redirect: 'manual' });
    const sc = r.headers.getSetCookie ? r.headers.getSetCookie() : [];
    sc.forEach(c => { const [kv] = c.split(';'); const [k, v] = kv.split('='); if (/Max-Age=0/i.test(c)) this.cookie = ''; else this.cookie = k + '=' + v; });
    const text = await r.text(); let data = null; try { data = JSON.parse(text); } catch (e) {}
    return { status: r.status, data, text, headers: r.headers, raw: r };
  }
  async login(id, password) { const r = await this.req('POST', '/api/v1/auth/login', { json: { id, password } }); if (r.status === 200) this.csrf = r.data.csrfToken; return r; }
}
function multipart(fields, file) {
  const boundary = '----bdtest' + Math.random().toString(16).slice(2), parts = [];
  for (const [k, v] of Object.entries(fields)) parts.push(Buffer.from('--' + boundary + '\r\nContent-Disposition: form-data; name="' + k + '"\r\n\r\n' + v + '\r\n'));
  if (file) { parts.push(Buffer.from('--' + boundary + '\r\nContent-Disposition: form-data; name="valid_id"; filename="' + file.name + '"\r\nContent-Type: ' + file.type + '\r\n\r\n')); parts.push(file.data); parts.push(Buffer.from('\r\n')); }
  parts.push(Buffer.from('--' + boundary + '--\r\n'));
  return { boundary, body: Buffer.concat(parts) };
}
